create or replace function public.invalidate_run(run_id uuid, reason_code text)
returns jsonb language plpgsql security definer set search_path = public, auth as $$
declare v_player uuid; v_changed boolean;
begin
  perform public.assert_operator();
  if nullif(trim(reason_code), '') is null then raise exception 'reason required'; end if;
  update public.runs set status = 'invalidated' where id = invalidate_run.run_id and status = 'verified' returning player_id into v_player;
  v_changed := found;
  if v_changed then
    delete from public.leaderboard_entries where public.leaderboard_entries.run_id = invalidate_run.run_id;
    delete from public.ghosts where public.ghosts.run_id = invalidate_run.run_id;
    insert into public.notifications(player_id, kind, run_id, reason) values (v_player, 'run_invalidated', invalidate_run.run_id, 'Your verified run was removed after a fair-play review: ' || reason_code);
  end if;
  insert into public.operator_audit(operator_id, action, run_id, player_id, reason_code) values (auth.uid(), 'invalidate_run', invalidate_run.run_id, v_player, reason_code);
  return jsonb_build_object('changed', v_changed, 'run_id', invalidate_run.run_id);
end;
$$;

create or replace function public.set_player_flag(player_id uuid, on boolean, note text default null)
returns jsonb language plpgsql security definer set search_path = public, auth as $$
declare v_changed boolean;
begin
  perform public.assert_operator();
  if on then
    update public.profiles set flagged_at = coalesce(flagged_at, now()) where id = set_player_flag.player_id;
    v_changed := found;
    if v_changed then insert into public.notifications(player_id, kind, reason) values (set_player_flag.player_id, 'player_flagged', coalesce(note, 'Your entries are under review.')); end if;
  else
    update public.profiles set flagged_at = null where id = set_player_flag.player_id and flagged_at is not null;
    v_changed := found;
    if v_changed then insert into public.notifications(player_id, kind, reason) values (set_player_flag.player_id, 'player_unflagged', 'Your entries are no longer under review.'); end if;
  end if;
  insert into public.operator_audit(operator_id, action, player_id, note) values (auth.uid(), case when on then 'set_player_flag' else 'clear_player_flag' end, set_player_flag.player_id, note);
  return jsonb_build_object('changed', v_changed, 'player_id', set_player_flag.player_id, 'flagged', on);
end;
$$;

create or replace function public.flag_player(player_id uuid, reason text)
returns jsonb language sql security definer set search_path = public as $$ select public.set_player_flag(player_id, true, reason); $$;
create or replace function public.unflag_player(player_id uuid)
returns jsonb language sql security definer set search_path = public as $$ select public.set_player_flag(player_id, false, null); $$;

grant execute on function public.invalidate_run(uuid, text), public.set_player_flag(uuid, boolean, text), public.flag_player(uuid, text), public.unflag_player(uuid) to authenticated;

create or replace function public.get_my_notifications(limit_count integer default 20)
returns setof public.notifications language sql stable security definer set search_path = public as $$
  select * from public.notifications where player_id = auth.uid() order by created_at desc limit greatest(1, least(limit_count, 100));
$$;

create or replace function public.mark_read(notification_id uuid)
returns boolean language sql security definer set search_path = public as $$
  update public.notifications set read_at = coalesce(read_at, now()) where id = mark_read.notification_id and player_id = auth.uid() returning true;
$$;

grant execute on function public.get_my_notifications(integer), public.mark_read(uuid) to authenticated;
comment on function public.assert_operator() is 'Operator JWT grant: update auth.users.app_metadata with {"role":"operator"}, then refresh the JWT.';
